// Builds apps/web/src/scripts/mailroute.gen.js from the scene (apps/web/scenes/mailroute.js, a hairline figure:
// mount() plus hairline({...})) and the hairline kernel it runs on (scripts/vendor/hairline-kernel.js: the package's
// src/core, MIT, Lucas Marques). The scene stays the one source: edit it, then run `node scripts/build-mailroute.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const at = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const kernel = readFileSync(at('scripts/vendor/hairline-kernel.js'), 'utf8');
const scene = readFileSync(at('apps/web/scenes/mailroute.js'), 'utf8');
const out = `// GENERATED by scripts/build-mailroute.mjs. Do not edit; change apps/web/scenes/mailroute.js instead.
// Kernel: @lucasmarkes/hairline src/core (MIT License, Copyright (c) Lucas Marques).
${kernel}
let spec = null;
const hairline = (s) => { spec = s; };
${scene}
export { HL, spec };
`;
writeFileSync(at('apps/web/src/scripts/mailroute.gen.js'), out);
console.log('mailroute.gen.js written');
