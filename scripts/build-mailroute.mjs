// Builds apps/web/src/scripts/mailroute.gen.js from the scene (docs/redesign/hairline/mailroute.js, written in the
// hairline-create format) and the hairline kernel it runs on (scripts/vendor/hairline-kernel.js: the package's src/core, MIT, Lucas Marques).
// The scene stays the one source: edit it, check it with look.mjs of the hairline-create skill, then run `node scripts/build-mailroute.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const at = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const kernel = readFileSync(at('scripts/vendor/hairline-kernel.js'), 'utf8');
const scene = readFileSync(at('docs/redesign/hairline/mailroute.js'), 'utf8');
const out = `// GENERATED by scripts/build-mailroute.mjs. Do not edit; change docs/redesign/hairline/mailroute.js instead.
// Kernel: @lucasmarkes/hairline src/core (MIT License, Copyright (c) Lucas Marques).
${kernel}
let spec = null;
const hairline = (s) => { spec = s; };
${scene}
export { HL, spec };
`;
writeFileSync(at('apps/web/src/scripts/mailroute.gen.js'), out);
console.log('mailroute.gen.js written');
